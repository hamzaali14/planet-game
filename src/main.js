import * as THREE from '../vendor/three.module.js';
import { OrbitControls } from '../vendor/OrbitControls.js';
import { createPlanet } from './planet.js';
import { createMoon } from './moon.js';
import { createStars } from './stars.js';
import { createClouds } from './clouds.js';
// Game core: later steps register systems (buildings, people, weather, quakes, aliens) via game.addSystem({update(dt){}}).
const renderer=new THREE.WebGLRenderer({antialias:true,alpha:true,powerPreference:'high-performance'});
renderer.setPixelRatio(Math.min(devicePixelRatio,1.75));renderer.setSize(innerWidth,innerHeight);
renderer.toneMapping=THREE.ACESFilmicToneMapping;renderer.toneMappingExposure=1.05;renderer.outputColorSpace=THREE.SRGBColorSpace;
renderer.setClearColor(0x000000,0);document.body.appendChild(renderer.domElement);
const scene=new THREE.Scene();
const camera=new THREE.PerspectiveCamera(45,innerWidth/innerHeight,0.05,600);camera.position.set(0,5,17);
scene.add(new THREE.HemisphereLight('#d6f1ff','#4f8aa8',1.6));
const sun=new THREE.DirectionalLight('#fff0dc',2.6);sun.position.set(14,16,18);scene.add(sun);
const fill=new THREE.DirectionalLight('#7fd6ff',0.6);fill.position.set(-15,-4,-8);scene.add(fill);
const planet=createPlanet();scene.add(planet.group);
const clouds=createClouds(planet.radius);planet.group.add(clouds.mesh);
const moon=createMoon();scene.add(moon.group);
scene.add(createStars());
const controls=new OrbitControls(camera,renderer.domElement);
Object.assign(controls,{enableDamping:true,dampingFactor:.08,enablePan:false,minDistance:planet.radius+0.6,maxDistance:40,rotateSpeed:.6,zoomSpeed:.9});
controls.touches={ONE:THREE.TOUCH.ROTATE,TWO:THREE.TOUCH.DOLLY_ROTATE};
export const game={scene,camera,renderer,planet,controls,spinPaused:false,addSystem:s=>systems.push(s)};
const systems=[{update:dt=>moon.update(dt)},{update:dt=>{planet.update(dt,camera);clouds.update(dt,camera);}},
  {update:dt=>{if(!game.spinPaused)planet.group.rotation.y+=dt*0.02;}}];
window.game=game;
const clock=new THREE.Clock();
renderer.setAnimationLoop(()=>{const dt=Math.min(clock.getDelta(),.1);
  controls.rotateSpeed=0.15+0.6*Math.min(1,(camera.position.length()-planet.radius)/15);
  systems.forEach(s=>s.update(dt));controls.update();renderer.render(scene,camera);});
addEventListener('resize',()=>{camera.aspect=innerWidth/innerHeight;camera.updateProjectionMatrix();renderer.setSize(innerWidth,innerHeight);});
import { createTown } from './town.js';
game.town=createTown(game);
